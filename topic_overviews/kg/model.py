def normalize_license_url(url: str) -> str:
    """Reduce a license URL to a comparable form: no scheme, "www.", trailing
    slash, ``/legalcode``, ``/deed.<lang>`` or ``.html``/``.txt``; lower case."""
    import re

    u = (url or "").strip().lower()
    u = re.sub(r"^https?://", "", u)
    u = re.sub(r"^www\.", "", u)
    u = u.rstrip("/")
    u = re.sub(r"/(legalcode|deed(\.[a-z-]+)?)$", "", u)
    u = re.sub(r"\.(html|txt)$", "", u)
    return u.rstrip("/")


def license_qid(url: str) -> str:
    """The license item for a license URL, or "" when the URL is not in the table."""
    return LICENSE_QIDS.get(normalize_license_url(url), "")


def qid_from_uri(uri: str) -> str:
    """Extract the trailing Q-id from an entity URI (or pass through a bare QID)."""
    return uri.rstrip("/").rsplit("/", 1)[-1]
